package gobusterdir

import (
	"errors"
	"fmt"
	"net/http"
	"net/url"
	"path"
	"strings"
)

// ValidateRecursion checks the recursion configuration at startup and rejects
// values that can never produce a consistent scan. Errors name the offending
// option so the conflict is actionable.
func (o *OptionsDir) ValidateRecursion() error {
	for _, pattern := range o.RecursionExcludePaths {
		if err := validatePathPattern("recursion-exclude-path", pattern); err != nil {
			return err
		}
	}

	for _, pattern := range o.RecursionExpandOnly {
		if err := validatePathPattern("recursion-expand-only-path", pattern); err != nil {
			return err
		}
	}

	// A path cannot be both excluded and "expand but do not report": the two
	// rules give opposite instructions for the same directory.
	for _, excluded := range o.RecursionExcludePaths {
		for _, expandOnly := range o.RecursionExpandOnly {
			if normalizePathPattern(excluded) == normalizePathPattern(expandOnly) {
				return fmt.Errorf("recursion-exclude-path and recursion-expand-only-path conflict on the same path %q", excluded)
			}
		}
	}

	// With an explicit positive status list, excluding every accepted status
	// would mean no directory could ever be expanded.
	if o.RecursionExcludeStatusP.Length() > 0 && o.StatusCodesParsed.Length() > 0 {
		for status := range o.StatusCodesParsed.Set {
			if !o.RecursionExcludeStatusP.Contains(status) {
				return nil
			}
		}
		return errors.New("recursion-exclude-status excludes every status code accepted by status-codes, so no directory could ever be expanded")
	}

	return nil
}

func validatePathPattern(option, pattern string) error {
	pattern = strings.TrimSpace(pattern)
	if pattern == "" {
		return fmt.Errorf("%s contains an empty path pattern", option)
	}
	if _, err := path.Match(pattern, "probe"); err != nil {
		return fmt.Errorf("invalid value for %s %q: %w", option, pattern, err)
	}
	return nil
}

func normalizePathPattern(pattern string) string {
	trimmed := strings.TrimSpace(pattern)
	trimmed = strings.TrimPrefix(trimmed, "/")
	return strings.TrimSuffix(trimmed, "/")
}

// matchesAnyPath reports whether urlPath matches one of the path patterns.
// Patterns without glob metacharacters match by path prefix, so a bare
// "admin" excludes "admin", "admin/", "admin/users" and so on. Patterns with
// glob metacharacters are evaluated against the whole path and against the
// final path segment, so "*.bak" also matches "admin/index.bak".
func matchesAnyPath(patterns []string, urlPath string) (string, bool) {
	cleaned := strings.TrimPrefix(path.Clean("/"+urlPath), "/")
	for _, raw := range patterns {
		pattern := strings.TrimSpace(raw)
		if pattern == "" {
			continue
		}
		pattern = strings.TrimPrefix(pattern, "/")
		pattern = strings.TrimSuffix(pattern, "/")

		if !strings.ContainsAny(pattern, "*?[\\") {
			if cleaned == pattern || strings.HasPrefix(cleaned, pattern+"/") {
				return raw, true
			}
			continue
		}

		if matched, err := path.Match(pattern, cleaned); err == nil && matched {
			return raw, true
		}
		if matched, err := path.Match(pattern, path.Base(cleaned)); err == nil && matched {
			return raw, true
		}
	}
	return "", false
}

// excludedFromRecursion applies the status and length based exclusion rules.
// These reuse the same parsing as the normal status-code and length filters.
// They only gate expansion: the hit itself is still reported according to the
// normal output filters, so the result set stays comparable to a single-layer
// run.
func (o *OptionsDir) excludedFromRecursion(statusCode int, size int64) bool {
	if o.RecursionExcludeStatusP.Contains(statusCode) {
		return true
	}
	if o.RecursionExcludeLenP.Contains(int(size)) {
		return true
	}
	return false
}

// isDirectoryPath applies the extension rule: a directory layer carries no
// extension, a file layer does. A leading dot (as in ".git" or ".well-known")
// is not an extension, while any other dot in the final segment marks the hit
// as a file. This means the extension-expanded requests generated by the
// wordlist are never expanded as directories.
func isDirectoryPath(rawPath string) bool {
	trimmed := strings.TrimSuffix(rawPath, "/")
	if trimmed == "" {
		// The root itself is a directory.
		return true
	}
	segment := path.Base(path.Clean("/" + trimmed))
	segment = strings.TrimLeft(segment, ".")
	return segment != "" && segment != "." && segment != "/" && !strings.Contains(segment, ".")
}

// recursiveTargetFor derives the directory to expand from a hit. It returns an
// empty string when the hit is a file, is excluded, or redirects to another
// host. Redirect targets are resolved relative to the request URL so both
// absolute and relative Location headers work.
func (d *GobusterDir) recursiveTargetFor(entity string, requestURL url.URL, statusCode int, header http.Header) string {
	if !d.globalopts.Recursion || d.globalopts.RecursionDepth == 0 {
		return ""
	}

	if location := header.Get("Location"); location != "" && statusCode >= 300 && statusCode < 400 {
		redirectURL, err := requestURL.Parse(location)
		if err != nil {
			return ""
		}
		// A redirect to another origin must never be followed for expansion.
		// The scheduler would reject it anyway; dropping it here keeps the
		// queue free of unusable targets.
		if d.rootURL == nil ||
			!strings.EqualFold(redirectURL.Scheme, d.rootURL.Scheme) ||
			!strings.EqualFold(redirectURL.Host, d.rootURL.Host) {
			return ""
		}
		// A redirect target only counts as a directory candidate when it names
		// a directory. The extension rule still applies: a target such as
		// "/index.php/" is a file-shaped path and must not be expanded.
		if !isDirectoryPath(redirectURL.Path) {
			return ""
		}
		redirectURL.RawQuery = ""
		redirectURL.Fragment = ""
		return redirectURL.String()
	}

	if !isDirectoryPath(entity) {
		return ""
	}

	target := requestURL
	target.RawQuery = ""
	target.Fragment = ""
	if !strings.HasSuffix(target.Path, "/") {
		target.Path = fmt.Sprintf("%s/", target.Path)
	}
	return target.String()
}

// recursionOutputDecision applies the path based rules to a hit. Patterns are
// checked against both the full request path and the layer-relative entity, so
// "admin" works at the root as well as for nested layers.
//
// A path exclusion only stops the directory from being expanded; the hit is
// still reported under the normal filters. "Expand only" is the opposite: the
// directory is expanded but the hit is hidden from the output.
func (d *GobusterDir) recursionOutputDecision(entity, fullPath string) (report bool, expand bool) {
	report = true
	expand = true

	matches := func(patterns []string) bool {
		if _, ok := matchesAnyPath(patterns, fullPath); ok {
			return true
		}
		_, ok := matchesAnyPath(patterns, entity)
		return ok
	}

	if matches(d.options.RecursionExcludePaths) {
		return true, false
	}

	if matches(d.options.RecursionExpandOnly) {
		report = false
	}

	return report, expand
}
